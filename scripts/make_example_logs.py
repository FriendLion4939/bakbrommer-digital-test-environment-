"""Generate the SYNTHETIC example logs in data/example_logs.

There are no real ride logs yet. To be able to test and demonstrate import,
replay and calibration, this script simulates a short test ride with a
vehicle that differs from the default profile in four "hidden" values, adds
realistic sensor noise, and writes the sensor readings in three file formats:

* example_ride_sd.csv        — as the STM32F7 might log to its SD card
* example_ride_can.log       — candump format, using data/can/bakbrommer_example.yaml
* example_ride_savvycan.csv  — the same CAN frames as a SavvyCAN export

Deliberate imperfections (to exercise the cleaning step): the CSV contains one
impossible speed value and one empty cell; the CAN log has a 1.5 s hole in the
battery message.

Usage:  python scripts/make_example_logs.py
"""

from __future__ import annotations

import numpy as np

from bakbrommer_twin import paths
from bakbrommer_twin.data_import.can_defs import load_definitions
from bakbrommer_twin.params import default_params, units
from bakbrommer_twin.scenarios.scenario import Scenario
from bakbrommer_twin.sim.result import RunResult
from bakbrommer_twin.sim.simulator import run_scenario

# The "real" vehicle of the example differs from the default profile like this.
HIDDEN_TRUTH: dict[str, float] = {
    "mass.chassis.mass": 150.0,  # kg (default 130)
    "tyre.rolling_resistance_scale": 1.3,  # (default 1.0)
    "aero.frontal_area": 1.15,  # m² (default 1.0)
    "battery.internal_resistance": 85.0,  # mΩ (default 60)
}
RIDE = Scenario.model_validate({
    "name": "Synthetic example ride",
    # A calm rider: corners well below the wheel-lift limit, so that a replay with
    # somewhat wrong parameters (open-loop steering!) stays out of trouble.
    "param_overrides": {**HIDDEN_TRUTH, "sim.random_seed": 2024,
                        "driver.max_lateral_accel": 1.3},
    "route": [
        {"type": "straight", "length_m": 160, "speed_kmh": 42},
        {"type": "straight", "length_m": 45, "speed_kmh": 42, "throttle": 0.0},
        {"type": "straight", "length_m": 90, "speed_kmh": 30},
        {"type": "arc", "radius_m": 22, "angle_deg": 180, "speed_kmh": 28},
        {"type": "straight", "length_m": 170, "speed_kmh": 46},
        {"type": "arc", "radius_m": 25, "angle_deg": -90, "speed_kmh": 30},
        {"type": "straight", "length_m": 90, "speed_kmh": 22},
    ],
    "end": {"time_limit_s": 150},
})
CSV_COLUMNS: tuple[tuple[str, str, str], ...] = (  # (column, sensor, unit)
    ("thr_pct", "throttle", "%"), ("brk_f_bar", "brake_front_pressure", "bar"),
    ("brk_r_bar", "brake_rear_pressure", "bar"), ("steer_deg", "steering_angle", "deg"),
    ("eng_rpm", "engine_speed", "rpm"), ("spd_kmh", "vehicle_speed", "km/h"),
    ("ws_fl_rpm", "wheel_speed_fl", "rpm"), ("ws_fr_rpm", "wheel_speed_fr", "rpm"),
    ("ws_r_rpm", "wheel_speed_r", "rpm"), ("acc_x", "accel_x", "m/s²"),
    ("acc_y", "accel_y", "m/s²"), ("acc_z", "accel_z", "m/s²"),
    ("gyr_x_dps", "gyro_x", "deg/s"), ("gyr_y_dps", "gyro_y", "deg/s"),
    ("gyr_z_dps", "gyro_z", "deg/s"), ("vbat_V", "battery_voltage", "V"),
    ("ibat_A", "battery_current", "A"), ("tmot_l_C", "motor_temp_l", "°C"),
    ("tmot_r_C", "motor_temp_r", "°C"))
CSV_EVERY = 2  # samples (50 Hz from the 100 Hz recording)
CAN_EVERY = {0x101: 1, 0x102: 2, 0x103: 1, 0x104: 1, 0x105: 5, 0x106: 10}
CAN_GAP = (30.0, 31.5)  # s without battery frames
CAN_EPOCH = 1_700_000_000.0  # arbitrary start of the candump clock, s
HEADER = ("# SYNTHETIC EXAMPLE DATA - generated by scripts/make_example_logs.py from the "
          "simulator, not measured on a vehicle.")


def _sensor(result: RunResult, sensor: str, unit: str) -> np.ndarray:
    if sensor == "ride_mode":
        return result["mode_request"]
    _, factor, offset = units.UNITS[unit]
    return (result[f"sens_{sensor}"] - offset) / factor


def write_csv(result: RunResult) -> None:
    """SD-card style CSV at 50 Hz with two deliberate flaws."""
    rows = [HEADER, ",".join(["t_ms", *(c for c, _, _ in CSV_COLUMNS), "mode"])]
    columns = [_sensor(result, sensor, unit) for _, sensor, unit in CSV_COLUMNS]
    for i in range(0, len(result["time"]), CSV_EVERY):
        cells = [f"{result['time'][i] * 1000:.0f}", *(f"{c[i]:.4g}" for c in columns),
                 f"{result['mode_request'][i]:.0f}"]
        if i == 1200:
            cells[6] = "999.9"  # impossible speed: sensor glitch
        if i == 2400:
            cells[17] = ""  # missing value
        rows.append(",".join(cells))
    (paths.example_logs_dir() / "example_ride_sd.csv").write_text("\n".join(rows) + "\n",
                                                                  encoding="utf-8")


def write_can(result: RunResult) -> None:
    """The same ride as CAN frames in candump and SavvyCAN format."""
    definitions = load_definitions(paths.can_dir() / "bakbrommer_example.yaml")
    dump, savvy = [], ["Time Stamp,ID,Extended,Dir,Bus,LEN,D1,D2,D3,D4,D5,D6,D7,D8"]
    time = result["time"]
    signals = {message.id: {s.name: _sensor(result, s.channel, s.unit) if s.channel else None
                            for s in message.signals} for message in definitions.messages}
    for i, now in enumerate(time):
        for message in definitions.messages:
            if i % CAN_EVERY[message.id]:
                continue
            if message.id == 0x105 and CAN_GAP[0] <= now < CAN_GAP[1]:
                continue
            values = {name: (float(series[i]) if series is not None else float(i % 256))
                      for name, series in signals[message.id].items()}
            data = message.encode(values)
            dump.append(f"({CAN_EPOCH + now:.6f}) can0 {message.id:03X}#{data.hex().upper()}")
            cells = [f"{now * 1e6:.0f}", f"{message.id:08X}", "false", "Rx", "0", str(len(data)),
                     *(f"{byte:02X}" for byte in data), *([""] * (8 - len(data)))]
            savvy.append(",".join(cells))
    folder = paths.example_logs_dir()
    (folder / "example_ride_can.log").write_text("\n".join(dump) + "\n", encoding="utf-8")
    (folder / "example_ride_savvycan.csv").write_text("\n".join(savvy) + "\n", encoding="utf-8")


def main() -> None:
    """Simulate the ride and write the three example files."""
    paths.example_logs_dir().mkdir(parents=True, exist_ok=True)
    result = run_scenario(default_params(), RIDE)
    write_csv(result)
    write_can(result)
    print(f"Wrote example logs ({result.meta.duration:.0f} s ride, ended: "
          f"{result.meta.end_reason}) to {paths.example_logs_dir()}")


if __name__ == "__main__":
    main()
